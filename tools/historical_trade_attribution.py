"""Research-only attribution of the shipped portfolio's historical closed trades.

No broker, order routing, optimization or strategy promotion. Trade records are
generated by the exact shipped historical backtester on hash-identified snapshots.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from collections import defaultdict
from decimal import Decimal
from pathlib import Path

from app.qualification.portable_artifact_codec import canonical_json_bytes
from app.strategy.cross_sectional_portfolio import (
    CrossSectionalPortfolioBacktester,
    CrossSectionalPortfolioPolicy,
    PortfolioTrade,
)
from app.strategy.cross_sectional_selection import CrossSectionalSelector
from app.strategy.position_management import PositionManagementPolicy
from app.strategy.reentry_confirmation import ReentryConfirmationPolicy
from tools.historical_portfolio_evidence import _common_timestamps


def _totals(trades: tuple[PortfolioTrade, ...]) -> dict[str, object]:
    gross = sum((t.gross_pnl_before_costs for t in trades), Decimal("0"))
    slippage = sum((t.slippage_cost for t in trades), Decimal("0"))
    fees = sum((t.entry_fee + t.exit_fee for t in trades), Decimal("0"))
    net = sum((t.net_pnl for t in trades), Decimal("0"))
    # Decimal's finite context can round differently when monetary sums are
    # associated in another order. Tolerance is <= 1e-8 USD per closed trade:
    # materially inconsistent cashflows must still fail closed.
    discrepancy = abs((gross - slippage - fees) - net)
    tolerance = Decimal("0.00000001") * max(1, len(trades))
    if discrepancy > tolerance:
        raise ValueError("closed trade PnL accounting is inconsistent")
    return {
        "trades": len(trades),
        "gross_pnl": str(gross),
        "slippage_cost": str(slippage),
        "fees": str(fees),
        "net_pnl_before_funding": str(net),
        "one_bar_trades": sum(t.holding_bars <= 1 for t in trades),
        "ambiguous_intrabar_exits": sum(t.ambiguous_intrabar_exit for t in trades),
        "gap_through_stops": sum(t.gap_through_stop for t in trades),
        "winners": sum(t.net_pnl > 0 for t in trades),
        "losers": sum(t.net_pnl < 0 for t in trades),
    }


def attribute_closed_trades(trades: tuple[PortfolioTrade, ...]) -> dict[str, object]:
    by_reason: dict[str, list[PortfolioTrade]] = defaultdict(list)
    by_symbol: dict[str, list[PortfolioTrade]] = defaultdict(list)
    by_holding: dict[str, list[PortfolioTrade]] = defaultdict(list)
    for trade in trades:
        by_reason[trade.exit_reason.value].append(trade)
        by_symbol[trade.symbol].append(trade)
        band = ("0-1" if trade.holding_bars <= 1 else
                "2-3" if trade.holding_bars <= 3 else "4+")
        by_holding[band].append(trade)
    return {
        "total": _totals(trades),
        "by_exit_reason": {key: _totals(tuple(value)) for key, value in sorted(by_reason.items())},
        "by_symbol": {key: _totals(tuple(value)) for key, value in sorted(by_symbol.items())},
        "by_holding_bars": {
            key: _totals(tuple(value)) for key, value in sorted(by_holding.items())
        },
    }


def run_attribution(
    *,
    bars_dir: Path,
    symbols: tuple[str, ...],
    opening_cash: Decimal = Decimal("10000"),
    fee_bps_per_fill: Decimal = Decimal("8"),
    slippage_bps: Decimal = Decimal("5"),
) -> dict[str, object]:
    if not symbols or symbols != tuple(sorted(set(symbols))):
        raise ValueError("symbols must be nonempty, unique and sorted")
    paths = [bars_dir / f"{symbol}_D.csv" for symbol in symbols]
    if any(not path.is_file() for path in paths):
        raise ValueError("one or more historical datasets are missing")
    loaded, timeline = _common_timestamps(paths)
    selected_times = set(timeline)
    bars = [bar for symbol in symbols for bar in loaded[symbol] if bar.timestamp in selected_times]
    selector = CrossSectionalSelector(top_k=2)
    policy = CrossSectionalPortfolioPolicy(
        opening_cash=opening_cash, fee_per_fill=Decimal("0"),
        fee_bps_per_fill=fee_bps_per_fill, slippage_bps=slippage_bps,
        maximum_gross_exposure_fraction=Decimal("0.60"),
        new_position_target_equity_fraction=Decimal("0.29"),
    )
    result = CrossSectionalPortfolioBacktester(
        selector=selector, portfolio_policy=policy,
        position_policy=PositionManagementPolicy(),
        reentry_policy=ReentryConfirmationPolicy(minimum_consecutive_eligible_bars=2),
    ).run(bars)
    identity = {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in paths}
    payload: dict[str, object] = {
        "schema_version": "astra-trade-attribution-research-v1",
        "research_only": True,
        "strategy_promotion_allowed": False,
        "evaluation_class": "REUSED_INSPECTED_HISTORY_DIAGNOSTIC_ONLY",
        "funding_modelled": False,
        "queue_position_modelled": False,
        "partial_fills_modelled": False,
        "symbols": list(symbols),
        "source_sha256": dict(sorted(identity.items())),
        "start": timeline[0].isoformat(),
        "end": timeline[-1].isoformat(),
        "cost_policy": {
            "fee_bps_per_fill": str(fee_bps_per_fill),
            "slippage_bps": str(slippage_bps),
        },
        "portfolio": {
            "opening_cash": str(result.opening_cash),
            "ending_equity": str(result.ending_equity),
            "total_pnl": str(result.total_pnl),
            "total_return_pre_funding": str(result.total_return),
            "closed_trade_count": result.closed_trade_count,
            "unrealized_and_open_position_pnl_included_in_portfolio": True,
        },
        "closed_trade_attribution": attribute_closed_trades(result.closed_trades),
        "limitations": [
            "Closed-trade net PnL excludes the unrealized PnL of final open positions",
            "No per-trade funding allocation; cannot infer funding-adjusted profitability",
            "No queue, partial-fill, market-impact or execution-latency modeling",
            "Existing inspected history is not an untouched out-of-sample holdout",
        ],
    }
    payload["evidence_sha256"] = hashlib.sha256(canonical_json_bytes(payload)).hexdigest()
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bars-dir", type=Path, required=True)
    parser.add_argument("--symbols", nargs="+", required=True)
    parser.add_argument("--fee-bps-per-fill", type=Decimal, default=Decimal("8"))
    parser.add_argument("--slippage-bps", type=Decimal, default=Decimal("5"))
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    report = run_attribution(
        bars_dir=args.bars_dir, symbols=tuple(sorted(args.symbols)),
        fee_bps_per_fill=args.fee_bps_per_fill, slippage_bps=args.slippage_bps,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report["closed_trade_attribution"], sort_keys=True, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
